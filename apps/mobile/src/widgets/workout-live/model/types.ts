/** Что сейчас происходит в тренировке — от этого зависят подпись и таймер на экране блокировки */
export type WorkoutLivePhase = 'warmup' | 'set' | 'rest' | 'restOver' | 'workout';

/**
 * Данные экрана блокировки. Уходят в нативный слой через JSON, поэтому только строки, числа и null.
 * Тексты собираем в приложении: макет виджета работает в изолированном рантайме без наших хелперов
 */
export type WorkoutLiveProps = {
  workoutId: number;
  /** Начало тренировки, мс: к нему возвращается счёт, когда отдых пропустили кнопкой уведомления */
  startedAt: number;
  title: string;
  exercise: string;
  /** «Подход 3 из 4», «Круг 2 из 3», «Разминка» */
  step: string;
  /** Цель подхода: план «Цель 8–12 повт.», без плана — «Прошлый раз 60 × 8»; пусто — нечего показать */
  target: string;
  /** Упражнения: сделано из всех */
  done: number;
  total: number;
  /** Подходы: сделано из всех по плану */
  setsDone: number;
  setsTotal: number;
  /** Подходов в каждом упражнении — сегменты прогресса Live Update на Android 16 */
  segments: number[];
  phase: WorkoutLivePhase;
  /** Подпись к таймеру: «Отдых», «Подход идёт» */
  label: string;
  /** Начало отсчёта, мс */
  from: number;
  /** Конец обратного отсчёта, мс; null — счёт вверх от from */
  to: number | null;
  /** Отсчёт стоит на паузе с этого момента, мс */
  pausedAt: number | null;
  /** Время без живого таймера для Android: «до 14:32», «с 14:20» */
  clock: string;
};
