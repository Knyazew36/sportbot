/**
 * Фраза на экран итога. Выбор по id тренировки, а не случайный: при возврате на итог
 * и перезагрузке фраза та же, а от тренировки к тренировке меняется
 */
export const motivationFor = (workoutId: number, gender: Gender | null | undefined): string => {
  const phrases = gender === 'MALE' ? MALE : gender === 'FEMALE' ? FEMALE : NEUTRAL
  return phrases[workoutId % phrases.length]!
}
